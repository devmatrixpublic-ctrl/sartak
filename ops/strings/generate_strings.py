"""Write app/src/main/res/values/strings.xml from reason_strings_en.json (plan 4.4).

Resource name for code F_NEW_PAYEE is `reason_f_new_payee`. Output is deterministic (ordered by
contracts/reason_codes.json) so validate_strings.py can detect drift.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
CODES = ROOT / "contracts" / "reason_codes.json"
SOURCE = Path(__file__).with_name("reason_strings_en.json")
XML_OUT = ROOT / "app" / "src" / "main" / "res" / "values" / "strings.xml"
HI_SOURCE = Path(__file__).with_name("reason_strings_hi.json")
HI_XML_OUT = ROOT / "app" / "src" / "main" / "res" / "values-hi" / "strings.xml"


def resource_name(code: str) -> str:
    return "reason_" + code.lower()


def android_escape(text: str) -> str:
    """XML-escape, then escape what Android's resource compiler treats specially."""
    return escape(text).replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')


def render_xml(strings: dict[str, str], codes: list[str] | None = None, source: str = "hand-written") -> str:
    order = codes or [c["code"] for c in json.loads(CODES.read_text(encoding="utf-8"))["codes"]]
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             f"<!-- GENERATED by ops/strings/generate_strings.py from reason_strings_en.json (source: {source}). Do not edit. -->",
             "<resources>"]
    for code in order:
        lines.append(f'    <string name="{resource_name(code)}">{android_escape(strings[code])}</string>')
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def main() -> int:
    doc = json.loads(SOURCE.read_text(encoding="utf-8"))
    XML_OUT.parent.mkdir(parents=True, exist_ok=True)
    XML_OUT.write_text(render_xml(doc["strings"], source=doc.get("source", "unknown")), encoding="utf-8", newline="\n")
    print(f"wrote {XML_OUT.relative_to(ROOT)}")
    hi = json.loads(HI_SOURCE.read_text(encoding="utf-8"))
    HI_XML_OUT.parent.mkdir(parents=True, exist_ok=True)
    HI_XML_OUT.write_text(render_xml(hi["strings"], source=hi.get("source", "unknown")).replace("from reason_strings_en.json", "from reason_strings_hi.json"),
                          encoding="utf-8", newline="\n")
    print(f"wrote {HI_XML_OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
